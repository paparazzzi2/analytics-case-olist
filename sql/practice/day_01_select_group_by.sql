-- ---------------------------------------------------------------------
-- Задача 1. Сколько заказов в каждом статусе
-- Бизнес-смысл: где процесс заказа обрывается
-- Результат: delivered 96 478 (97,0%); потеряно 1 234 (1,2%):
--   canceled 625, unavailable 609; в процессе 1 729 (1,7%):
--   shipped 1 107, invoiced 314, processing 301, created 5, approved 2
-- Вывод: процесс почти не теряет заказы, фокус проекта — сроки и качество
-- ---------------------------------------------------------------------
SELECT order_status, COUNT(*) AS orders
FROM orders
GROUP BY order_status
ORDER BY orders DESC;


-- ---------------------------------------------------------------------
-- Задача 2. Сколько доставленных заказов без даты доставки
-- Бизнес-смысл: проверка гипотезы DQ-02 о причине пропусков дат
-- Результат: 8. Из 2 965 пропусков 2 957 — недоставленные заказы (норма),
--   8 — аномалии: статус delivered без даты (DQ-13), исключаются из сроков
-- Урок: условие "AND NOT NULL" без колонки возвращает 0 всегда —
--   запрос выполняется без ошибки, но ответ ложный
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS delivered_without_date
FROM orders
WHERE order_status = 'delivered'
  AND order_delivered_customer_date IS NULL;
